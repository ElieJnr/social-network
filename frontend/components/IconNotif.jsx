function GetIcon({ type, ...props }) {
    switch (type) {
        case "follow"://color-blue
            return UserPlusIcon(props)
            break
        case "msg"://color-red
            return MessageCircleIcon(props)
            break
        case "event"://color-yellow
            return CalendarIcon(props)
            break
        case "invitation"://color-
            return UsersIcon(props)
            break

    }
}

